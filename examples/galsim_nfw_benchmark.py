import matplotlib.tri as mtri

sys.path.insert(0, os.path.join(os.path.dirname(__file__), ".."))

from femmi.catalog import reconstruct_catalog, kaiser_squires_binned


# --------------------------------------------------------------------------- #
# GalSim NFW truth
# --------------------------------------------------------------------------- #
def _require_galsim():
    try:
        import galsim
        return galsim
    except ImportError:
        sys.exit("This benchmark needs GalSim.  Install it with:  pip install galsim")


def nfw_truth(x_arcmin, y_arcmin, halos, z_source=1.0):
    """Analytic NFW convergence and (unreduced) shear at galaxy positions.

    halos : list of dicts with keys mass (Msun), conc, z (lens redshift),
            pos (x, y) in arcmin. Fields add in the weak regime.
    Returns kappa_true, gamma1_true, gamma2_true (all arrays over the galaxies).
    """
    galsim = _require_galsim()
    xs = np.asarray(x_arcmin, float) * 60.0        # arcmin -> arcsec (GalSim unit)
    ys = np.asarray(y_arcmin, float) * 60.0
    kap = np.zeros(xs.size)
    g1  = np.zeros(xs.size)
    g2  = np.zeros(xs.size)
    for h in halos:
        halo = galsim.NFWHalo(
            mass=float(h["mass"]), conc=float(h["conc"]), redshift=float(h["z"]),
            halo_pos=galsim.PositionD(h["pos"][0] * 60.0, h["pos"][1] * 60.0),
            omega_m=0.3, omega_lam=0.7)
        pos = (xs, ys)
        kap += np.asarray(halo.getConvergence(pos=pos, z_s=z_source,
                                              units=galsim.arcsec))
        s1, s2 = halo.getShear(pos=pos, z_s=z_source, units=galsim.arcsec,
                               reduced=False)
        g1 += np.asarray(s1)
        g2 += np.asarray(s2)
    return kap, g1, g2


def _nfw_g(x):
    """Wright & Brainerd (2000) deflection function g(x) = ln(x/2) + F(x)."""
    x = np.asarray(x, float); g = np.empty_like(x)
    lo = x < 1 - 1e-6; hi = x > 1 + 1e-6; eq = ~(lo | hi)
    xl = np.clip(x[lo], 1e-8, None); xh = x[hi]
    g[lo] = np.log(xl / 2) + np.arccosh(1 / xl) / np.sqrt(1 - xl**2)
    g[hi] = np.log(xh / 2) + np.arccos(1 / xh) / np.sqrt(xh**2 - 1)
    g[eq] = 1 + np.log(0.5)
    return g


# radial lensing-potential shape: dpsi/dx = 4 kappa_s rs^2 g(x)/x, so the shape
# is the running integral of g(x)/x (the constant 4 kappa_s rs^2 is fit per halo).
_XG = np.logspace(-5, 4, 60000)
_GG = _nfw_g(_XG) / _XG
_PSI_INTEG = np.concatenate([[0.0], np.cumsum(0.5 * (_GG[1:] + _GG[:-1]) * np.diff(_XG))])


def _psi_shape(x):
    return np.interp(x, _XG, _PSI_INTEG)


def nfw_potential(x_arcmin, y_arcmin, halos, grid_n=161):
    """Analytic NFW lensing potential psi_true at the galaxies (arcmin^2).

    The radial shape is the exact analytic NFW form (integral of the WB2000
    deflection); the per-halo amplitude is fixed by a least-squares match of the
    finite-difference Laplacian of the analytic potential to 2*kappa_GalSim on a
    grid. Returns (psi_true_gal, verify_resid) where verify_resid is the relative
    ||lap(psi) - 2 kappa|| residual -- a transparent check that psi_true really
    solves the lensing Poisson equation for the GalSim convergence (~1e-3 when
    correct). Everything is in the arcmin frame the reconstructions use."""
    galsim = _require_galsim()
    x = np.asarray(x_arcmin, float); y = np.asarray(y_arcmin, float)
    pad = 0.05 * (np.ptp(x) + np.ptp(y)) + 1e-6
    gx = np.linspace(x.min() - pad, x.max() + pad, grid_n)
    gy = np.linspace(y.min() - pad, y.max() + pad, grid_n)
    GX, GY = np.meshgrid(gx, gy); dgx = gx[1] - gx[0]; dgy = gy[1] - gy[0]

    kap = np.zeros(GX.size)
    shapes_grid, shapes_gal = [], []
    for h in halos:
        halo = galsim.NFWHalo(mass=float(h["mass"]), conc=float(h["conc"]),
                              redshift=float(h["z"]), omega_m=0.3, omega_lam=0.7,
                              halo_pos=galsim.PositionD(h["pos"][0] * 60.0, h["pos"][1] * 60.0))
        rs_am = halo.rs_arcsec / 60.0
        kap += np.asarray(halo.getConvergence(pos=(GX.ravel() * 60.0, GY.ravel() * 60.0),
                                              z_s=1.0, units=galsim.arcsec))
        shapes_grid.append(_psi_shape(np.hypot(GX - h["pos"][0], GY - h["pos"][1]) / rs_am))
        shapes_gal.append(_psi_shape(np.hypot(x - h["pos"][0], y - h["pos"][1]) / rs_am))
    kap = kap.reshape(GX.shape)

    def lap(f):
        return ((np.roll(f, 1, 1) + np.roll(f, -1, 1) - 2 * f) / dgx**2 +
                (np.roll(f, 1, 0) + np.roll(f, -1, 0) - 2 * f) / dgy**2)

    m = np.ones(GX.shape, bool); m[:2] = m[-2:] = m[:, :2] = m[:, -2:] = False
    for h in halos:                                  # drop the singular halo cores
        m &= np.hypot(GX - h["pos"][0], GY - h["pos"][1]) > 3 * max(dgx, dgy)
    Phi = np.stack([lap(s)[m] for s in shapes_grid], axis=1)
    target = 2.0 * kap[m]
    A, *_ = np.linalg.lstsq(Phi, target, rcond=None)
    resid = float(np.linalg.norm(Phi @ A - target) / (np.linalg.norm(target) + 1e-30))
    psi_gal = sum(Ai * sg for Ai, sg in zip(A, shapes_gal))
    return psi_gal, resid


def potential_from_kappa_fft(kappa_grid, dx, dy):
    """KS-style potential: solve lap(psi) = 2 kappa on a periodic grid.
    psi(k) = -2 kappa(k) / k^2. This is the only route KS has to a potential."""
    ny, nx = kappa_grid.shape
    kx = 2 * np.pi * np.fft.fftfreq(nx, d=dx)[None, :]
    ky = 2 * np.pi * np.fft.fftfreq(ny, d=dy)[:, None]
    k2 = kx**2 + ky**2; k2[0, 0] = 1.0
    psi_f = -2.0 * np.fft.fft2(kappa_grid) / k2
    psi_f[0, 0] = 0.0
    return np.fft.ifft2(psi_f).real


def bullet_like(sep_arcmin=2.5):
    """Two-halo Bullet-like config: massive main + lighter bullet, offset along x.
    Masses/conc are the approximate observed system; the separation is set in
    arcmin so it maps onto the FEMMI working frame directly."""
    return [
        dict(mass=1.0e15, conc=4.0, z=0.3, pos=(-0.5 * sep_arcmin, 0.0)),
        dict(mass=2.5e14, conc=5.0, z=0.3, pos=(+0.5 * sep_arcmin, 0.0)),
    ]


def single_halo():
    return [dict(mass=1.0e15, conc=4.0, z=0.3, pos=(0.0, 0.0))]


# --------------------------------------------------------------------------- #
# shared kappa -> gamma FFT forward (identical for both methods -> fair)
# --------------------------------------------------------------------------- #
def shear_from_kappa_grid(kappa_grid):
    """KS forward relation gamma(k) = exp(2 i phi_k) kappa(k) on a periodic grid."""
    ny, nx = kappa_grid.shape
    kx = np.fft.fftfreq(nx)[None, :]
    ky = np.fft.fftfreq(ny)[:, None]
    k2 = kx**2 + ky**2
    k2[0, 0] = 1.0
    D = ((kx**2 - ky**2) + 2j * kx * ky) / k2      # exp(2 i phi_k)
    kap_f = np.fft.fft2(kappa_grid)
    g = np.fft.ifft2(D * kap_f)
    return g.real, g.imag


def bin_galaxy_to_grid(x, y, vals, grid_size=64):
    """Bin scattered galaxy values onto a regular grid; return grid, pixel
    indices (yi, xi), finite mask, and the pixel spacings (dx, dy) in arcmin."""
    m = np.isfinite(vals)
    ext = (x.min(), x.max(), y.min(), y.max())
    xi = np.clip(((x - ext[0]) / (ext[1] - ext[0] + 1e-12) * (grid_size - 1)).astype(int),
                 0, grid_size - 1)
    yi = np.clip(((y - ext[2]) / (ext[3] - ext[2] + 1e-12) * (grid_size - 1)).astype(int),
                 0, grid_size - 1)
    grid = np.zeros((grid_size, grid_size)); cnt = np.zeros_like(grid)
    np.add.at(grid, (yi[m], xi[m]), vals[m]); np.add.at(cnt, (yi[m], xi[m]), 1.0)
    grid[cnt > 0] /= cnt[cnt > 0]
    dx = (ext[1] - ext[0]) / (grid_size - 1); dy = (ext[3] - ext[2]) / (grid_size - 1)
    return grid, yi, xi, m, dx, dy


def predict_shear_at_galaxies(x, y, kappa_hat, grid_size=64):
    """Bin kappa_hat, forward-model to shear via the shared FFT operator, and
    sample back at the galaxies. One common forward for every method -> fair."""
    grid, yi, xi, m, _, _ = bin_galaxy_to_grid(x, y, kappa_hat, grid_size)
    g1g, g2g = shear_from_kappa_grid(grid)
    return g1g[yi, xi], g2g[yi, xi], m


def shear_consistency(x, y, kappa_hat, g1_obs, g2_obs, sigma, grid_size=64,
                      g1_true=None, g2_true=None):
    """Data-space self-consistency of a reconstruction.

    Returns (chi2_dof, pred_l2):
      chi2_dof : sum ||gamma_hat - gamma_obs||^2 / (2 N sigma^2). This is the
        real-data metric -- it needs only the observed shears and the known
        shape-noise sigma, no truth map. ~1 => the reconstruction explains the
        shears down to the noise floor; >1 under-fits, <1 over-fits.
      pred_l2  : ||gamma_hat - gamma_true|| / ||gamma_true||, the predictive
        shear accuracy against the NOISELESS truth. Sim-only (needs gamma_true);
        this is the discriminating number that the noisy chi2 washes out.
    """
    g1h, g2h, m = predict_shear_at_galaxies(x, y, kappa_hat, grid_size)
    resid2 = (g1h[m] - g1_obs[m])**2 + (g2h[m] - g2_obs[m])**2
    chi2_dof = float(resid2.sum() / (2 * m.sum() * sigma**2 + 1e-30))
    pred_l2 = np.nan
    if g1_true is not None:
        num = np.hypot(g1h[m] - g1_true[m], g2h[m] - g2_true[m])
        den = np.hypot(g1_true[m], g2_true[m])
        pred_l2 = float(np.linalg.norm(num) / (np.linalg.norm(den) + 1e-30))
    return chi2_dof, pred_l2


# --------------------------------------------------------------------------- #
# driver
# --------------------------------------------------------------------------- #
def _mass_centroid(x, y, kap):
    w = np.clip(np.nan_to_num(kap), 0.0, None); s = float(w.sum())
    if s <= 0:
        return (float(np.mean(x)), float(np.mean(y)))
    return (float(np.sum(w * x) / s), float(np.sum(w * y) / s))


def run(args):
    rng = np.random.default_rng(args.seed)
    halos = bullet_like(args.separation) if args.halos == 2 else single_halo()

    # galaxies uniform over a square field (arcmin)
    L = args.field / 2.0
    x = rng.uniform(-L, L, args.n_gal)
    y = rng.uniform(-L, L, args.n_gal)
    kap_t, g1_t, g2_t = nfw_truth(x, y, halos, z_source=args.z_source)

    # drop the strong-lensing cores (weak approximation invalid), then noise
    keep = kap_t < args.kappa_max
    x, y, kap_t, g1_t, g2_t = (a[keep] for a in (x, y, kap_t, g1_t, g2_t))
    g1o = g1_t + rng.normal(0, args.shape_noise, x.size)
    g2o = g2_t + rng.normal(0, args.shape_noise, x.size)
    print(f"  {args.halos}-halo truth: {x.size} galaxies, kappa_true peak={kap_t.max():.2f}, "
          f"shape_noise={args.shape_noise}")

    center = _mass_centroid(x, y, kap_t) if args.center_on == "mass" \
        else (float(np.mean(x)), float(np.mean(y)))
    R = float(np.hypot(x - center[0], y - center[1]).max())
    print(f"  mesh/gauge center = ({center[0]:+.3f}, {center[1]:+.3f})  "
          f"[center_on={args.center_on}]  R={R:.3f}")

    # ---- FEMMI ----
    print("\n[FEMMI] catalog-native FEM-BEM MAP ...")
    fem = reconstruct_catalog(x, y, g1o, g2o, center=center, n_boundary=args.n_boundary,
                              use_morozov=True, noise_source="bmode",
                              noise_std=args.noise_std, wiener_length=args.wiener_length,
                              maxiter=args.maxiter, verbose=True)
    kfem = fem.kappa_gal

    # ---- KS ----
    print("[KS] bin -> smooth -> FFT ...")
    ext = (x.min(), x.max(), y.min(), y.max())
    kks = kaiser_squires_binned(x, y, g1o, g2o, grid_size=args.grid_size,
                                smoothing_px=2.0, extent=ext,
                                eval_pts=np.column_stack([x, y]))

    # ---- potentials: FEMMI native psi_hat vs KS FFT-derived psi_hat vs analytic truth ----
    print("[psi] analytic NFW potential + FEMMI native / KS FFT potentials ...")
    psi_true, psi_resid = nfw_potential(x, y, halos)
    # FEMMI solves for psi directly -- take its native potential at the galaxies
    psi_nodes = np.asarray(fem.ops.psi_from_kappa(fem.kappa_nodes))
    cm = fem.catalog_mesh
    psi_fem = np.full(len(x), np.nan); psi_fem[cm.source_index] = psi_nodes[cm.galaxy_nodes]
    # KS has no native potential: integrate its kappa_hat grid, psi(k) = -2 kappa/k^2
    kks_grid, yi, xi, _, dxg, dyg = bin_galaxy_to_grid(x, y, kks, args.grid_size)
    psi_ks_grid = potential_from_kappa_fft(kks_grid, dxg, dyg)
    psi_ks = psi_ks_grid[yi, xi]

    def l2_psi(psi_hat):
        m = np.isfinite(psi_hat) & np.isfinite(psi_true)
        a = psi_hat[m] - psi_hat[m].mean(); b = psi_true[m] - psi_true[m].mean()  # gauge: zero-mean
        return float(np.linalg.norm(a - b) / (np.linalg.norm(b) + 1e-30))

    # ---- metrics ----
    def l2(k):
        m = np.isfinite(k)
        return float(np.linalg.norm(k[m] - kap_t[m]) / (np.linalg.norm(kap_t[m]) + 1e-30))

    def corr(k):
        m = np.isfinite(k)
        return float(np.corrcoef(k[m], kap_t[m])[0, 1])

    chi_f, pl_f = shear_consistency(x, y, kfem, g1o, g2o, args.shape_noise,
                                    args.grid_size, g1_t, g2_t)
    chi_k, pl_k = shear_consistency(x, y, kks, g1o, g2o, args.shape_noise,
                                    args.grid_size, g1_t, g2_t)

    print("\n==================== benchmark ====================")
    print(f"  truth-space   L2(kappa)       FEMMI={l2(kfem):.3f}   KS={l2(kks):.3f}")
    print(f"  truth-space   corr(kappa)     FEMMI={corr(kfem):+.3f}  KS={corr(kks):+.3f}")
    print(f"  data-space    chi2/dof(obs)   FEMMI={chi_f:.3f}   KS={chi_k:.3f}   "
          f"(~1 = explains shear to the noise floor; real-data metric)")
    print(f"  shear-space   L2(gamma,truth) FEMMI={pl_f:.3f}   KS={pl_k:.3f}   "
          f"(predictive accuracy vs noiseless shear; lower is better)")
    print(f"  potential     L2(psi,truth)   FEMMI={l2_psi(psi_fem):.3f}   KS={l2_psi(psi_ks):.3f}   "
          f"(FEMMI native psi vs KS FFT-derived; truth verified to {psi_resid:.1e})")
    print(f"  peak recovery FEMMI={np.nanmax(kfem):.2f}  KS={np.nanmax(kks):.2f}  "
          f"(truth {kap_t.max():.2f})")
    print("===================================================")

    _figure(x, y, kap_t, kfem, kks, args)
    return dict(kap_t=kap_t, kfem=kfem, kks=kks)


def _figure(x, y, kap_t, kfem, kks, args):
    tri = mtri.Triangulation(x, y)
    # mask degenerate triangles spanning the core-cut hole / convex-hull slivers
    xt, yt = x[tri.triangles], y[tri.triangles]
    edges = np.hypot(np.diff(xt[:, [0, 1, 2, 0]], axis=1),
                     np.diff(yt[:, [0, 1, 2, 0]], axis=1)).max(axis=1)
    tri.set_mask(edges > 6.0 * np.median(edges))
    vmax = float(np.nanpercentile(kap_t, 99)) or 1.0
    panels = [("truth kappa (GalSim NFW)", kap_t),
              ("FEMMI kappa_hat", kfem), ("KS kappa_hat", kks)]
    fig, axes = plt.subplots(1, 3, figsize=(15, 4.6), facecolor="#1a1a1a")
    for ax, (title, d) in zip(axes, panels):
        ax.set_facecolor("#111111")
        tc = ax.tripcolor(tri, np.nan_to_num(d), cmap="hot", vmin=0.0, vmax=vmax, shading="gouraud")
        ax.set_title(title, color="white"); ax.set_aspect("equal")
        ax.tick_params(colors="#aaa")
        fig.colorbar(tc, ax=ax, fraction=0.046)
    fig.suptitle(f"GalSim {args.halos}-halo NFW benchmark  (independent analytic truth)",
                 color="white", fontsize=13, y=1.02)
    fig.tight_layout()
    out = os.path.join(os.path.dirname(__file__), "..", "outputs",
                       f"fig_galsim_nfw_{args.halos}halo.png")
    fig.savefig(out, dpi=150, bbox_inches="tight", facecolor="#1a1a1a")
    plt.close(fig)
    print(f"\nwrote {os.path.normpath(out)}")


def main():
    ap = argparse.ArgumentParser(description="GalSim NFW weak-lensing benchmark: FEMMI vs KS")
    ap.add_argument("--halos", type=int, choices=[1, 2], default=2,
                    help="1 = single NFW; 2 = Bullet-like merger (default)")
    ap.add_argument("--separation", type=float, default=2.5,
                    help="two-halo separation (arcmin)")
    ap.add_argument("--field", type=float, default=10.0, help="field size (arcmin)")
    ap.add_argument("--n-gal", type=int, default=4000, help="galaxy count before core cut")
    ap.add_argument("--shape-noise", type=float, default=0.25,
                    help="per-component intrinsic ellipticity sigma")
    ap.add_argument("--kappa-max", type=float, default=0.6,
                    help="drop galaxies inside the strong-lensing core")
    ap.add_argument("--z-source", type=float, default=1.0)
    ap.add_argument("--grid-size", type=int, default=64)
    ap.add_argument("--n-boundary", type=int, default=96)
    ap.add_argument("--maxiter", type=int, default=2000)
    ap.add_argument("--noise-std", type=float, default=None,
                    help="override Morozov noise floor (else B-mode auto estimate)")
    ap.add_argument("--wiener-length", type=float, default=None,
                    help="Matern-1/2 prior length in arcmin (default 0.2 * ring "
                         "radius); smaller = sharper peaks")
    ap.add_argument("--center-on", choices=["field", "mass"], default="mass")
    ap.add_argument("--seed", type=int, default=1)
    run(ap.parse_args())


if __name__ == "__main__":
    main()
