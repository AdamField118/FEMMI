"""
examples/galsim_nfw_benchmark.py
Synthetic weak-lensing benchmark with an INDEPENDENT ground truth: GalSim's
analytic NFWHalo (Wright & Brainerd 2000 / Bartelmann 1996 closed forms) is the
simulator, and FEMMI and Kaiser-Squires are the competing reconstructions. There
is deliberately NO overlap with FEMMI's numerical Poisson machinery -- GalSim
evaluates the NFW lensing field analytically -- so a reviewer cannot argue the
data were generated by the same discretisation FEMMI inverts.

Two configurations (Marshall & Bridle style two-experiment structure):
  --halos 1 : single NFW halo. The easy case; shows both methods converge.
  --halos 2 : two NFW halos in a Bullet-like merger geometry (main + bullet with
              an impact parameter). Multiple peaks, a saddle, overlapping shear
              -- much closer to the real application.

Evaluation (three metrics):
  1. Truth-space  L2(kappa) : ||kappa_hat - kappa_true|| / ||kappa_true|| on the
     galaxies, against the GalSim convergence. Direct, but privileges kappa.
  2. Data-space  chi2/dof   : forward-model each reconstruction's kappa_hat back
     to shear (a shared grid-FFT kappa->gamma operator, identical for both
     methods), then chi2/dof = sum||gamma_hat - gamma_obs||^2 / (2 N sigma^2)
     against the OBSERVED shears and the known shape-noise sigma. This needs no
     truth map, so it is the metric that survives on a real cluster: ~1 means the
     reconstruction explains the shear down to the noise floor, >1 under-fits.
     (A plain ||gamma_hat-gamma_obs||/||gamma_obs|| ratio is noise-floored to ~1
     and cannot discriminate -- chi2/dof normalises by the noise instead.)
  3. Shear-space L2(gamma,truth) : ||gamma_hat - gamma_true|| / ||gamma_true||
     against the NOISELESS simulated shear. Sim-only, but this is the
     discriminating predictive-accuracy number the noisy chi2 washes out.
  4. Potential  L2(psi,truth) : FEMMI reconstructs psi DIRECTLY, so it is scored
     with its native potential (psi_from_kappa); KS has no native potential, so
     its psi_hat is integrated from kappa_hat by FFT (psi(k) = -2 kappa/k^2). The
     truth is the analytic NFW lensing potential, verified to solve lap(psi)=2kappa
     for the GalSim convergence. This is the metric that most reconstruction
     papers cannot report, because they do not solve for the potential at all.

Requires GalSim (pip install galsim).  Run on the HPC:
    python examples/galsim_nfw_benchmark.py --halos 2 --n-gal 4000 \
        --shape-noise 0.25 --maxiter 3000 --center-on mass

Truth kappa/gamma come from GalSim; ONLY the image-generation step is skipped
(we sample the analytic shear at galaxy positions directly, which is what a
perfect shape measurement would recover -- add GalSim rendering + shape
measurement later if you want to fold in measurement bias).
"""

